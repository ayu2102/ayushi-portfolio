function setupDockNavigation() {
  const header = document.getElementById("siteHeader");
  if (!header) return;

  setupMobileNavigation(header);

  const trigger = header.querySelector(".dock-trigger");
  const brand = header.querySelector(".standalone-brand");
  const nav = header.querySelector(".nav-shell");
  let hideTimer;

  const openDock = () => {
    window.clearTimeout(hideTimer);
    header.classList.add("is-dock-open");
  };

  const closeDock = () => {
    hideTimer = window.setTimeout(() => {
      if (header.matches(":hover") || header.contains(document.activeElement)) return;
      header.classList.remove("is-dock-open");
    }, 300);
  };

  [trigger, brand, nav].forEach((item) => {
    if (!item) return;
    item.addEventListener("pointerenter", openDock);
    item.addEventListener("pointerleave", closeDock);
    item.addEventListener("focusin", openDock);
  });

  header.addEventListener("focusout", closeDock);
  document.addEventListener("keydown", (event) => {
    if (event.key !== "Escape") return;
    if (!header.contains(document.activeElement)) header.classList.remove("is-dock-open");
  });
}

function setupMobileNavigation(header) {
  const toggle = header.querySelector(".mobile-menu-toggle");
  const nav = header.querySelector(".nav-shell");
  if (!toggle || !nav) return;

  const closeMenu = () => {
    header.classList.remove("is-mobile-menu-open");
    document.body.classList.remove("mobile-nav-open");
    toggle.setAttribute("aria-expanded", "false");
  };

  const openMenu = () => {
    header.classList.add("is-mobile-menu-open");
    document.body.classList.add("mobile-nav-open");
    toggle.setAttribute("aria-expanded", "true");
  };

  toggle.addEventListener("click", () => {
    if (header.classList.contains("is-mobile-menu-open")) {
      closeMenu();
    } else {
      openMenu();
    }
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

