function setupTeardownReveal() {
  const cards = document.querySelectorAll(".workspace-card, .principle-panel");
  if (!cards.length) return;

  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    cards.forEach((card) => card.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, {
    rootMargin: "0px 0px -12% 0px",
    threshold: 0.18
  });

  cards.forEach((card) => observer.observe(card));
}

function setupPrinciplesTracker() {
  const desktopQuery = window.matchMedia("(min-width: 901px)");
  const panels = [...document.querySelectorAll(".principle-panel")];
  if (!desktopQuery.matches || !panels.length) return;

  const setActive = (activePanel) => {
    panels.forEach((panel) => {
      panel.classList.toggle("is-active", panel === activePanel);
    });
  };

  setActive(panels[0]);

  panels.forEach((panel) => {
    panel.addEventListener("pointerenter", () => setActive(panel));
    panel.addEventListener("focusin", () => setActive(panel));
  });

  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  const observer = new IntersectionObserver((entries) => {
    const activeEntry = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

    if (activeEntry) setActive(activeEntry.target);
  }, {
    rootMargin: "-28% 0px -45% 0px",
    threshold: [0.2, 0.35, 0.5, 0.65]
  });

  panels.forEach((panel) => observer.observe(panel));
}

function setupPoemOverlay() {
  const list = document.getElementById("poemList");
  const overlay = document.getElementById("poemOverlay");
  if (!list || !overlay) return;

  if (!poems.length) {
    list.hidden = true;
    return;
  }

  const title = document.getElementById("poemTitle");
  const body = document.getElementById("poemBody");
  const meta = document.getElementById("poemMeta");
  const closeButton = overlay.querySelector("[data-poem-close]");
  const prevButton = overlay.querySelector("[data-poem-prev]");
  const nextButton = overlay.querySelector("[data-poem-next]");
  let activeIndex = 0;
  let lastFocus = null;

  list.hidden = false;
  list.innerHTML = poems.map((poem, index) => `
    <button class="poem-row" type="button" data-poem-index="${index}">
      <span>${String(index + 1).padStart(2, "0")}</span>
      <strong>${poem.title}</strong>
      <small>Read verse &#8594;</small>
    </button>
  `).join("");

  const renderPoem = (index) => {
    const poem = poems[index];
    if (!poem) return;
    activeIndex = index;
    meta.textContent = `Verse ${String(index + 1).padStart(2, "0")}`;
    title.textContent = poem.title;
    body.innerHTML = poem.bodyHtml;
    prevButton.disabled = index === 0;
    nextButton.disabled = index === poems.length - 1;
  };

  const openPoem = (index, opener) => {
    lastFocus = opener;
    renderPoem(index);
    overlay.hidden = false;
    document.body.classList.add("has-poem-open");
    closeButton.focus();
  };

  const closePoem = () => {
    overlay.hidden = true;
    document.body.classList.remove("has-poem-open");
    if (lastFocus) lastFocus.focus();
  };

  list.addEventListener("click", (event) => {
    const row = event.target.closest("[data-poem-index]");
    if (!row) return;
    openPoem(Number(row.dataset.poemIndex), row);
  });

  closeButton.addEventListener("click", closePoem);
  prevButton.addEventListener("click", () => renderPoem(Math.max(0, activeIndex - 1)));
  nextButton.addEventListener("click", () => renderPoem(Math.min(poems.length - 1, activeIndex + 1)));

  overlay.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closePoem();
      return;
    }

    if (event.key !== "Tab") return;
    const focusable = [...overlay.querySelectorAll("button:not([disabled]), [href], [tabindex]:not([tabindex='-1'])")];
    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  });
}

function createSvg(tag) {
  return document.createElementNS("http://www.w3.org/2000/svg", tag);
}

function shuffle(items) {
  return items
    .map((item) => ({ item, sort: Math.random() }))
    .sort((a, b) => a.sort - b.sort)
    .map(({ item }) => item);
}

function random(min, max) {
  return Math.random() * (max - min) + min;
}

function clamp(value, min, max) {
  return Math.min(Math.max(value, min), max);
}
