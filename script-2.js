function setupNewDelhiClock() {
  const clocks = document.querySelectorAll("#newDelhiTime");
  if (!clocks.length) return;

  const formatter = new Intl.DateTimeFormat("en-IN", {
    timeZone: "Asia/Kolkata",
    hour: "2-digit",
    minute: "2-digit",
    hour12: true
  });

  const updateClock = () => {
    const time = formatter.format(new Date()).toUpperCase();
    clocks.forEach((clock) => {
      clock.textContent = `IST ${time}`;
    });
  };

  updateClock();
  window.setInterval(updateClock, 60000);
}

function runHeroWordCycle() {
  const target = document.getElementById("heroWord");
  if (!target || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  const slot = target.closest(".hero__word-slot");
  let index = 0;

  const typeWord = (word, character = 0) => {
    slot?.classList.add("is-animating");
    target.textContent = word.slice(0, character);

    if (character < word.length) {
      window.setTimeout(() => typeWord(word, character + 1), 68);
      return;
    }

    slot?.classList.remove("is-animating");
    window.setTimeout(eraseWord, 4600);
  };

  const eraseWord = () => {
    slot?.classList.add("is-animating");
    const visibleWord = target.textContent;

    if (visibleWord.length > 0) {
      target.textContent = visibleWord.slice(0, -1);
      window.setTimeout(eraseWord, 52);
      return;
    }

    index = (index + 1) % heroWords.length;
    window.setTimeout(() => typeWord(heroWords[index], 0), 180);
  };

  window.setTimeout(eraseWord, 4600);
}

function setupHeroPortraitReveal() {
  const hero = document.getElementById("hero");
  const layer = hero?.querySelector(".hero__portrait-reveal");
  const image = layer?.querySelector("img");
  const content = hero?.querySelector(".hero__content");
  if (!hero || !layer || !image || !content) return;

  const touchDevice = window.matchMedia("(hover: none), (pointer: coarse)").matches;
  if (touchDevice) return;

  const rightZoneStart = 0.38;
  const hintPosition = { x: 0.7, y: 0.46 };
  const trailLifetime = 820;
  const brushRadius = 148;
  const trail = [];
  let hideTimer = 0;
  let trailFrame = 0;
  let lastPoint = null;
  let pointerActive = false;

  const getReadableTextRects = (element) => {
    if (!element) return [];

    const range = document.createRange();
    range.selectNodeContents(element);
    const rects = Array.from(range.getClientRects()).filter((rect) => rect.width && rect.height);
    range.detach();

    return rects.length ? rects : [element.getBoundingClientRect()];
  };

  const getTextSafeRects = () => [
      content.querySelector(".eyebrow"),
      ...content.querySelectorAll("h1 span"),
      content.querySelector(".hero__copy")
    ]
    .filter(Boolean)
    .flatMap(getReadableTextRects);

  const setHintPosition = () => {
    layer.style.setProperty("--hero-portrait-x", `${hintPosition.x * 100}%`);
    layer.style.setProperty("--hero-portrait-y", `${hintPosition.y * 100}%`);
  };

  const clearTrail = () => {
    trail.length = 0;
    lastPoint = null;
    pointerActive = false;
    image.style.removeProperty("-webkit-mask-image");
    image.style.removeProperty("mask-image");
    image.style.removeProperty("-webkit-mask-size");
    image.style.removeProperty("mask-size");
    image.style.removeProperty("-webkit-mask-position");
    image.style.removeProperty("mask-position");
    if (trailFrame) {
      window.cancelAnimationFrame(trailFrame);
      trailFrame = 0;
    }
  };

  const showHint = () => {
    window.clearTimeout(hideTimer);
    clearTrail();
    setHintPosition();
    hero.classList.remove("is-portrait-active");
    hero.classList.add("is-portrait-hint");
  };

  const renderTrail = (now = performance.now()) => {
    for (let index = trail.length - 1; index >= 0; index -= 1) {
      const age = now - trail[index].time;
      if (age > trailLifetime) trail.splice(index, 1);
    }

    if (trail.length) {
      const masks = trail.map((point, index) => {
        const age = now - point.time;
        const life = clamp(1 - age / trailLifetime, 0, 1);
        const isNewest = index === trail.length - 1 && pointerActive;
        const alpha = isNewest ? 1 : Math.min(0.72, 0.12 + life * 0.5);
        const radius = brushRadius * (isNewest ? 1.08 : 0.76 + life * 0.18);
        return `radial-gradient(circle ${radius.toFixed(1)}px at ${point.x.toFixed(1)}px ${point.y.toFixed(1)}px, rgba(0, 0, 0, ${alpha.toFixed(3)}) 0%, rgba(0, 0, 0, ${(alpha * 0.92).toFixed(3)}) 32%, rgba(0, 0, 0, ${(alpha * 0.46).toFixed(3)}) 66%, transparent 100%)`;
      }).join(", ");

      image.style.setProperty("-webkit-mask-image", masks);
      image.style.setProperty("mask-image", masks);
      image.style.setProperty("-webkit-mask-size", "auto");
      image.style.setProperty("mask-size", "auto");
      image.style.setProperty("-webkit-mask-position", "0 0");
      image.style.setProperty("mask-position", "0 0");
      trailFrame = window.requestAnimationFrame(renderTrail);
      return;
    }

    image.style.setProperty("-webkit-mask-image", "radial-gradient(circle 0px at 50% 50%, transparent 100%)");
    image.style.setProperty("mask-image", "radial-gradient(circle 0px at 50% 50%, transparent 100%)");
    trailFrame = 0;
    if (!pointerActive) showHint();
  };

  const addTrailPoint = (x, y) => {
    const now = performance.now();
    const shouldAdd = !lastPoint ||
      Math.hypot(x - lastPoint.x, y - lastPoint.y) > 8 ||
      now - lastPoint.time > 34;

    if (!shouldAdd) return;

    lastPoint = { x, y, time: now };
    trail.push(lastPoint);
    if (trail.length > 14) trail.shift();
    if (!trailFrame) trailFrame = window.requestAnimationFrame(renderTrail);
  };

  const updatePortrait = (event) => {
    const heroRect = hero.getBoundingClientRect();
    const imageRect = image.getBoundingClientRect();
    const textSafeRects = getTextSafeRects();
    const x = event.clientX - heroRect.left;
    const isPortraitArea =
      event.clientX >= imageRect.left - 24 &&
      event.clientX <= imageRect.right + 24 &&
      event.clientY >= imageRect.top - 24 &&
      event.clientY <= imageRect.bottom + 24;
    const isRightZone = x >= heroRect.width * rightZoneStart || isPortraitArea;
    const isTextSafe = textSafeRects.some((rect) =>
      event.clientX >= rect.left - 18 &&
      event.clientX <= rect.right + 18 &&
      event.clientY >= rect.top - 22 &&
      event.clientY <= rect.bottom + 22
    );

    if (!isRightZone || isTextSafe) {
      showHint();
      return;
    }

    pointerActive = true;
    window.clearTimeout(hideTimer);
    hero.classList.remove("is-portrait-hint");
    hero.classList.add("is-portrait-active");
    addTrailPoint(event.clientX - imageRect.left, event.clientY - imageRect.top);
  };

  showHint();
  hero.addEventListener("mousemove", updatePortrait);
  hero.addEventListener("mouseleave", () => {
    pointerActive = false;
    hideTimer = window.setTimeout(showHint, 760);
  });
}

function setupMobileHeroScratchReveal() {
  const hero = document.getElementById("hero");
  const layer = hero?.querySelector(".hero__portrait-reveal");
  const canvas = layer?.querySelector(".hero__portrait-scratch");
  if (!hero || !layer || !canvas) return;

  const mobileQuery = window.matchMedia("(max-width: 900px), (hover: none) and (pointer: coarse)");
  if (!mobileQuery.matches) return;

  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  let width = 0;
  let height = 0;
  let animationFrame = 0;
  let t = 0;

  const paintCover = () => {
    ctx.globalCompositeOperation = "source-over";
    ctx.clearRect(0, 0, width, height);

    const paper = ctx.createLinearGradient(0, 0, width, height);
    paper.addColorStop(0, "rgba(246, 245, 240, 0.94)");
    paper.addColorStop(0.52, "rgba(235, 234, 228, 0.9)");
    paper.addColorStop(1, "rgba(216, 222, 201, 0.82)");
    ctx.fillStyle = paper;
    ctx.fillRect(0, 0, width, height);

    ctx.save();
    ctx.globalAlpha = 0.28;
    ctx.strokeStyle = "rgba(104, 119, 86, 0.09)";
    ctx.lineWidth = 1;
    for (let x = 0; x <= width; x += 34) {
      ctx.beginPath();
      ctx.moveTo(x, 0);
      ctx.lineTo(x, height);
      ctx.stroke();
    }
    for (let y = 0; y <= height; y += 34) {
      ctx.beginPath();
      ctx.moveTo(0, y);
      ctx.lineTo(width, y);
      ctx.stroke();
    }
    ctx.restore();

    const glow = ctx.createRadialGradient(width * 0.32, height * 0.16, 0, width * 0.32, height * 0.16, Math.max(width, height) * 0.46);
    glow.addColorStop(0, "rgba(250, 250, 250, 0.24)");
    glow.addColorStop(0.42, "rgba(240, 217, 168, 0.1)");
    glow.addColorStop(1, "rgba(240, 217, 168, 0)");
    ctx.fillStyle = glow;
    ctx.fillRect(0, 0, width, height);
  };

  const revealAt = (x, y, radius) => {
    ctx.save();
    ctx.globalCompositeOperation = "destination-out";
    const reveal = ctx.createRadialGradient(x, y, 0, x, y, radius);
    reveal.addColorStop(0, "rgba(0, 0, 0, 0.98)");
    reveal.addColorStop(0.55, "rgba(0, 0, 0, 0.86)");
    reveal.addColorStop(0.82, "rgba(0, 0, 0, 0.34)");
    reveal.addColorStop(1, "rgba(0, 0, 0, 0)");
    ctx.fillStyle = reveal;
    ctx.beginPath();
    ctx.arc(x, y, radius, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
  };

  const resizeCanvas = () => {
    const rect = layer.getBoundingClientRect();
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    width = Math.max(1, Math.round(rect.width));
    height = Math.max(1, Math.round(rect.height));
    canvas.width = Math.round(width * dpr);
    canvas.height = Math.round(height * dpr);
    canvas.style.width = `${width}px`;
    canvas.style.height = `${height}px`;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    // Cover is painted ONCE here. It is never repainted again after this point —
    // that's what makes the reveal below permanent instead of a repeating loop.
    paintCover();
    t = 0;

    // Reduced-motion visitors get an immediate, permanent reveal across all three
    // bands instead of watching the animation.
    if (reducedMotion) {
      const brush = Math.max(85, Math.min(width, height) * 0.22);
      revealAt(width * 0.5, height * 0.24, brush);
      revealAt(width * 0.5, height * 0.49, brush);
      revealAt(width * 0.5, height * 0.74, brush);
    }
  };

  const animate = () => {
    t += 0.022;
    const brush = Math.max(85, Math.min(width, height) * 0.22);

    // Boustrophedon zigzag: three horizontal bands, alternating left-right / right-left,
    // exactly like a hand scratching a card back and forth — not one smooth orbit.
    // Loops continuously (ambient motion), but revealAt() only ever erases, so nothing
    // already revealed is ever covered again — permanent, per the scratch-card spec.
    const bands = 3;
    const cycle = t % bands;
    const band = Math.floor(cycle);
    const progress = cycle - band;
    const goingRight = band % 2 === 0;
    const travel = goingRight ? progress : 1 - progress;

    const x = width * (0.1 + travel * 0.8);
    const bandY = 0.24 + (band / (bands - 1)) * 0.5;
    const y = height * bandY + Math.sin(progress * Math.PI) * height * 0.03;

    revealAt(x, y, brush);
    animationFrame = window.requestAnimationFrame(animate);
  };

  resizeCanvas();

  if (!reducedMotion) {
    animationFrame = window.requestAnimationFrame(animate);
  }

  window.addEventListener("resize", resizeCanvas);
  if ("ResizeObserver" in window) {
    const observer = new ResizeObserver(() => resizeCanvas());
    observer.observe(layer);
  }

  document.addEventListener("visibilitychange", () => {
    if (document.hidden && animationFrame) {
      window.cancelAnimationFrame(animationFrame);
      animationFrame = 0;
      return;
    }

    if (!document.hidden && !animationFrame && !reducedMotion) {
      animationFrame = window.requestAnimationFrame(animate);
    }
  });
}

function setupHeroClarityField() {
  const hero = document.getElementById("hero");
  const canvas = document.getElementById("heroClarityField");
  const content = hero?.querySelector(".hero__content");
  if (!hero || !canvas || !content) return;

  const ctx = canvas.getContext("2d");
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const touchDevice = window.matchMedia("(hover: none)").matches;
  const pointer = { active: false, x: 0, y: 0, easedX: 0, easedY: 0 };
  const ribbons = [
    { start: [0.12, 0.34], c1: [0.36, 0.05], c2: [0.72, 0.02], end: [0.92, 0.28], phase: 0.2, width: 1.5 },
    { start: [0.16, 0.56], c1: [0.42, 0.2], c2: [0.78, 0.22], end: [0.96, 0.52], phase: 1.1, width: 1.2 },
    { start: [0.28, 0.88], c1: [0.48, 0.62], c2: [0.72, 0.64], end: [0.94, 0.78], phase: 2.4, width: 1.35 },
    { start: [0.56, 0.78], c1: [0.7, 0.68], c2: [0.89, 0.86], end: [1.04, 0.68], phase: 3.3, width: 1.1 },
    { start: [-0.02, 0.88], c1: [0.12, 0.74], c2: [0.26, 0.96], end: [0.42, 0.82], phase: 4.1, width: 0.95 },
    { start: [0.7, 0.13], c1: [0.82, 0.22], c2: [0.84, 0.52], end: [0.98, 0.7], phase: 5.4, width: 1.15 }
  ];

  let width = 0;
  let height = 0;
  let safeRect = { left: 0, top: 0, right: 0, bottom: 0 };
  let particles = [];
  let animationFrame = 0;

  const getSafeInfluence = (x, y, feather = 150) => {
    const dx = Math.max(safeRect.left - x, 0, x - safeRect.right);
    const dy = Math.max(safeRect.top - y, 0, y - safeRect.bottom);
    if (dx === 0 && dy === 0) return 1;
    return clamp(1 - Math.hypot(dx, dy) / feather, 0, 1);
  };

  const isInsideSafeArea = (x, y, padding = 0) => (
    x >= safeRect.left - padding &&
    x <= safeRect.right + padding &&
    y >= safeRect.top - padding &&
    y <= safeRect.bottom + padding
  );

  const createParticles = () => {
    const perimeterZones = [
      [0.02, 0.16, 0.08, 0.95],
      [0.78, 0.99, 0.04, 0.95],
      [0.14, 0.92, 0.04, 0.18],
      [0.08, 0.96, 0.76, 0.98],
      [0.62, 0.96, 0.24, 0.7]
    ];
    const count = width < 760 ? 18 : 36;
    particles = [];

    for (let index = 0; index < count; index += 1) {
      const zone = perimeterZones[index % perimeterZones.length];
      let x = random(zone[0] * width, zone[1] * width);
      let y = random(zone[2] * height, zone[3] * height);
      let attempts = 0;

      while (isInsideSafeArea(x, y, 48) && attempts < 60) {
        x = random(zone[0] * width, zone[1] * width);
        y = random(zone[2] * height, zone[3] * height);
        attempts += 1;
      }

      if (!isInsideSafeArea(x, y, 42)) {
        particles.push({
          x,
          y,
          radius: random(0.75, 2.7),
          alpha: random(0.12, 0.34),
          glow: random(5, 18),
          warm: Math.random() > 0.36,
          phase: random(0, Math.PI * 2)
        });
      }
    }
  };

  const resizeCanvas = () => {
    const rect = hero.getBoundingClientRect();
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    width = Math.max(1, Math.round(rect.width));
    height = Math.max(1, Math.round(rect.height));
    canvas.width = Math.round(width * dpr);
    canvas.height = Math.round(height * dpr);
    canvas.style.width = `${width}px`;
    canvas.style.height = `${height}px`;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

    const heroRect = hero.getBoundingClientRect();
    const protectedElements = [
      content.querySelector(".eyebrow"),
      content.querySelector("h1"),
      content.querySelector(".hero__copy")
    ].filter(Boolean);
    const protectedRects = protectedElements.map((element) => element.getBoundingClientRect());
    const contentRect = protectedRects.reduce((rect, next) => ({
      left: Math.min(rect.left, next.left),
      top: Math.min(rect.top, next.top),
      right: Math.max(rect.right, next.right),
      bottom: Math.max(rect.bottom, next.bottom)
    }), protectedRects[0] || content.getBoundingClientRect());

    safeRect = {
      left: Math.max(0, contentRect.left - heroRect.left - 80),
      top: Math.max(0, contentRect.top - heroRect.top - 70),
      right: Math.min(width, contentRect.right - heroRect.left + 82),
      bottom: Math.min(height, contentRect.bottom - heroRect.top + 78)
    };

    createParticles();
  };

  const drawField = (time) => {
    const breath = reducedMotion ? 0.5 : (Math.sin(time / 5200) + 1) / 2;
    const fieldA = ctx.createRadialGradient(width * 0.66, height * 0.5, 0, width * 0.66, height * 0.5, width * 0.58);
    fieldA.addColorStop(0, `rgba(250, 250, 250, ${0.16 + breath * 0.055})`);
    fieldA.addColorStop(0.24, `rgba(237, 221, 181, ${0.16 + breath * 0.04})`);
    fieldA.addColorStop(0.52, `rgba(163, 177, 138, ${0.1 + breath * 0.035})`);
    fieldA.addColorStop(1, "rgba(246, 245, 240, 0)");
    ctx.fillStyle = fieldA;
    ctx.fillRect(0, 0, width, height);

    const fieldB = ctx.createRadialGradient(width * 0.86, height * 0.7, 0, width * 0.86, height * 0.7, width * 0.46);
    fieldB.addColorStop(0, "rgba(250, 250, 250, 0.14)");
    fieldB.addColorStop(0.35, "rgba(218, 190, 142, 0.12)");
    fieldB.addColorStop(0.68, "rgba(163, 177, 138, 0.07)");
    fieldB.addColorStop(1, "rgba(246, 245, 240, 0)");
    ctx.fillStyle = fieldB;
    ctx.fillRect(0, 0, width, height);

    const halo = ctx.createRadialGradient(width * 0.58, height * 0.48, width * 0.24, width * 0.58, height * 0.48, width * 0.52);
    halo.addColorStop(0, "rgba(246, 245, 240, 0)");
    halo.addColorStop(0.54, `rgba(255, 250, 226, ${0.07 + breath * 0.025})`);
    halo.addColorStop(0.61, `rgba(164, 190, 168, ${0.055 + breath * 0.018})`);
    halo.addColorStop(0.68, `rgba(250, 250, 250, ${0.09 + breath * 0.025})`);
    halo.addColorStop(0.76, "rgba(246, 245, 240, 0)");
    ctx.fillStyle = halo;
    ctx.fillRect(0, 0, width, height);
  };

  const drawCursorResponse = () => {
    if (!pointer.active || touchDevice || reducedMotion) return;
    const textSafety = getSafeInfluence(pointer.easedX, pointer.easedY, 260);
    const alpha = 0.18 * (1 - textSafety);
    if (alpha < 0.01) return;

    const glow = ctx.createRadialGradient(pointer.easedX, pointer.easedY, 0, pointer.easedX, pointer.easedY, 430);
    glow.addColorStop(0, `rgba(250, 250, 250, ${alpha * 0.48})`);
    glow.addColorStop(0.34, `rgba(241, 224, 181, ${alpha * 0.32})`);
    glow.addColorStop(0.64, `rgba(163, 177, 138, ${alpha * 0.2})`);
    glow.addColorStop(1, "rgba(246, 245, 240, 0)");
    ctx.fillStyle = glow;
    ctx.fillRect(0, 0, width, height);
  };

  const drawRibbon = (ribbon, time) => {
    const drift = reducedMotion ? 0 : Math.sin(time / 6800 + ribbon.phase) * 18;
    const pointerLift = pointer.active && !touchDevice && !reducedMotion
      ? 1 - getSafeInfluence(pointer.easedX, pointer.easedY, 260)
      : 0;
    const points = [ribbon.start, ribbon.c1, ribbon.c2, ribbon.end].map((point, index) => {
      const baseX = point[0] * width;
      const baseY = point[1] * height;
      const influence = pointerLift * clamp(1 - Math.hypot(pointer.easedX - baseX, pointer.easedY - baseY) / 420, 0, 1);
      return {
        x: baseX + drift * (index % 2 === 0 ? 0.55 : -0.32) + (pointer.easedX - baseX) * influence * 0.032,
        y: baseY + Math.cos(time / 7600 + ribbon.phase) * 12 + (pointer.easedY - baseY) * influence * 0.024
      };
    });

    const safeFade = 1 - Math.max(...points.map((point) => getSafeInfluence(point.x, point.y, 180))) * 0.72;
    if (safeFade < 0.18) return;

    const alpha = (0.19 + pointerLift * 0.065) * safeFade;
    ctx.save();
    ctx.lineCap = "round";
    ctx.lineWidth = ribbon.width;
    ctx.shadowBlur = 18;
    ctx.shadowColor = "rgba(250, 250, 246, 0.32)";
    ctx.beginPath();
    ctx.moveTo(points[0].x, points[0].y);
    ctx.bezierCurveTo(points[1].x, points[1].y, points[2].x, points[2].y, points[3].x, points[3].y);
    ctx.strokeStyle = `rgba(255, 253, 243, ${alpha})`;
    ctx.stroke();

    ctx.beginPath();
    ctx.moveTo(points[0].x, points[0].y + 7);
    ctx.bezierCurveTo(points[1].x, points[1].y + 5, points[2].x, points[2].y + 9, points[3].x, points[3].y + 6);
    ctx.strokeStyle = `rgba(174, 202, 178, ${alpha * 0.58})`;
    ctx.lineWidth = Math.max(0.65, ribbon.width * 0.7);
    ctx.stroke();

    ctx.beginPath();
    ctx.moveTo(points[0].x, points[0].y - 9);
    ctx.bezierCurveTo(points[1].x, points[1].y - 6, points[2].x, points[2].y - 12, points[3].x, points[3].y - 8);
    ctx.strokeStyle = `rgba(235, 204, 150, ${alpha * 0.36})`;
    ctx.lineWidth = Math.max(0.5, ribbon.width * 0.48);
    ctx.stroke();
    ctx.restore();
  };

  const drawSweep = (time) => {
    if (reducedMotion) return;
    const cycle = 14000;
    const progress = (time % cycle) / cycle;
    if (progress > 0.52) return;

    const alpha = Math.sin(progress / 0.52 * Math.PI) * 0.075;
    const x = width * (0.52 + progress * 0.62);

    ctx.save();
    ctx.translate(x, height * 0.55);
    ctx.rotate(-0.16);
    const sweep = ctx.createLinearGradient(-90, 0, 90, 0);
    sweep.addColorStop(0, "rgba(250, 250, 250, 0)");
    sweep.addColorStop(0.5, `rgba(250, 250, 250, ${alpha})`);
    sweep.addColorStop(1, "rgba(250, 250, 250, 0)");
    ctx.fillStyle = sweep;
    ctx.fillRect(-110, -height, 220, height * 2);
    ctx.restore();
  };

  const drawParticles = (time) => {
    particles.forEach((particle) => {
      const safety = getSafeInfluence(particle.x, particle.y, 110);
      if (safety > 0.22) return;
      const cursorGlow = pointer.active && !touchDevice && !reducedMotion
        ? clamp(1 - Math.hypot(pointer.easedX - particle.x, pointer.easedY - particle.y) / 240, 0, 1) * 0.18
        : 0;
      const breath = reducedMotion ? 0 : (Math.sin(time / 3600 + particle.phase) + 1) * 0.055;
      const alpha = particle.alpha + breath + cursorGlow;

      ctx.beginPath();
      ctx.arc(particle.x, particle.y, particle.radius + particle.glow, 0, Math.PI * 2);
      ctx.fillStyle = particle.warm
        ? `rgba(238, 206, 143, ${alpha * 0.11})`
        : `rgba(250, 250, 250, ${alpha * 0.13})`;
      ctx.fill();

      ctx.beginPath();
      ctx.arc(particle.x, particle.y, particle.radius, 0, Math.PI * 2);
      ctx.fillStyle = particle.warm
        ? `rgba(255, 248, 222, ${alpha * 0.92})`
        : `rgba(174, 202, 178, ${alpha * 0.72})`;
      ctx.fill();
    });
  };

  const quietSafeZone = () => {
    const centerX = safeRect.left + (safeRect.right - safeRect.left) * 0.34;
    const centerY = safeRect.top + (safeRect.bottom - safeRect.top) * 0.5;
    const radius = Math.max(safeRect.right - safeRect.left, safeRect.bottom - safeRect.top) * 0.86;
    const gradient = ctx.createRadialGradient(centerX, centerY, 0, centerX, centerY, radius);
    gradient.addColorStop(0, "rgba(246, 245, 240, 0.52)");
    gradient.addColorStop(0.54, "rgba(246, 245, 240, 0.2)");
    gradient.addColorStop(0.82, "rgba(246, 245, 240, 0.055)");
    gradient.addColorStop(1, "rgba(246, 245, 240, 0)");
    ctx.fillStyle = gradient;
    ctx.fillRect(0, 0, width, height);
  };

  const draw = (time = 0) => {
    if (pointer.active) {
      pointer.easedX += (pointer.x - pointer.easedX) * 0.045;
      pointer.easedY += (pointer.y - pointer.easedY) * 0.045;
    }

    ctx.clearRect(0, 0, width, height);
    drawField(time);
    drawCursorResponse();
    ribbons.forEach((ribbon) => drawRibbon(ribbon, time));
    drawSweep(time);
    drawParticles(time);
    quietSafeZone();

    if (!reducedMotion) animationFrame = window.requestAnimationFrame(draw);
  };

  const updatePointer = (event) => {
    const rect = hero.getBoundingClientRect();
    pointer.active = true;
    pointer.x = event.clientX - rect.left;
    pointer.y = event.clientY - rect.top;
    if (!pointer.easedX && !pointer.easedY) {
      pointer.easedX = pointer.x;
      pointer.easedY = pointer.y;
    }
  };

  resizeCanvas();
  draw();

  if (!reducedMotion) {
    animationFrame = window.requestAnimationFrame(draw);
    window.addEventListener("resize", resizeCanvas);
    if (!touchDevice) {
      hero.addEventListener("pointermove", updatePointer);
      hero.addEventListener("pointerleave", () => {
        pointer.active = false;
      });
    }
  }

  window.addEventListener("pagehide", () => {
    if (animationFrame) window.cancelAnimationFrame(animationFrame);
  });
}

function runConstellationLoader() {
  const loader = document.getElementById("loader");
  const sky = document.getElementById("constellation");
  if (!loader || !sky) return;

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    loader.classList.add("is-hidden");
    return;
  }

  const nodeCount = window.innerWidth < 620 ? 5 : 7;
  const words = shuffle([...helloWords]).slice(0, nodeCount);
  const points = createConstellationPoints(nodeCount);
  const svg = createSvg("svg");
  svg.setAttribute("viewBox", "0 0 100 100");
  svg.setAttribute("preserveAspectRatio", "none");
  sky.appendChild(svg);

  const nodes = points.map((point, index) => {
    if (index > 0) {
      const line = createSvg("line");
      line.setAttribute("x1", points[index - 1].x);
      line.setAttribute("y1", points[index - 1].y);
      line.setAttribute("x2", point.x);
      line.setAttribute("y2", point.y);
      line.setAttribute("pathLength", "1");
      line.classList.add("constellation-line");
      svg.appendChild(line);
      point.line = line;
    }

    const node = document.createElement("div");
    node.className = "constellation-node";
    node.style.left = `${point.x}%`;
    node.style.top = `${point.y}%`;
    node.innerHTML = `<div class="constellation-node__dot"></div><div class="constellation-node__label">${words[index]}</div>`;
    sky.appendChild(node);
    return { node, line: point.line };
  });

  // Safety net: no matter what happens with the animation math above, the loader
  // is force-hidden after 2.4s regardless. This guarantees it can never block the
  // page indefinitely, even in an edge case this function's own timing doesn't cover.
  window.setTimeout(() => loader.classList.add("is-hidden"), 2400);

  nodes.forEach((item, index) => {
    window.setTimeout(() => {
      item.node.classList.add("is-visible");
      if (item.line) item.line.classList.add("is-visible");
    }, 200 + index * 150);
  });

  const exitDelay = 200 + nodeCount * 150 + 300;
  window.setTimeout(() => loader.classList.add("is-blinking"), exitDelay);
  window.setTimeout(() => loader.classList.add("is-hidden"), exitDelay + 300);
}

function createConstellationPoints(count) {
  const points = [];
  const left = 10;
  const right = 90;
  const band = (right - left) / (count - 1);

  for (let index = 0; index < count; index += 1) {
    const baseX = left + band * index;
    const x = clamp(baseX + random(-3.4, 3.4), 8, 92);
    const y = clamp(random(24, 66) + (index % 2 === 0 ? -5 : 5), 18, 70);
    points.push({ x: Number(x.toFixed(2)), y: Number(y.toFixed(2)) });
  }

  return points;
}

