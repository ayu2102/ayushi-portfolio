function setupWritingListSmoothScroll() {
  const list = document.querySelector(".writing-list");
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (!list || reducedMotion) return;

  let targetScroll = list.scrollTop;
  let animationFrame = null;

  const maxScroll = () => Math.max(0, list.scrollHeight - list.clientHeight);

  const animateScroll = () => {
    const distance = targetScroll - list.scrollTop;

    if (Math.abs(distance) < 0.5) {
      list.scrollTop = targetScroll;
      animationFrame = null;
      return;
    }

    list.scrollTop += distance * 0.18;
    animationFrame = requestAnimationFrame(animateScroll);
  };

  list.addEventListener("wheel", (event) => {
    const maximum = maxScroll();
    if (!maximum || Math.abs(event.deltaY) < 1) return;

    const isAtTop = list.scrollTop <= 0 && event.deltaY < 0;
    const isAtBottom = list.scrollTop >= maximum - 1 && event.deltaY > 0;
    if (isAtTop || isAtBottom) return;

    event.preventDefault();
    targetScroll = Math.max(0, Math.min(maximum, targetScroll + event.deltaY));

    if (!animationFrame) {
      animationFrame = requestAnimationFrame(animateScroll);
    }
  }, { passive: false });

  list.addEventListener("scroll", () => {
    if (!animationFrame) targetScroll = list.scrollTop;
  }, { passive: true });
}

function setupScrollSpy() {
  const links = [...document.querySelectorAll(".nav-links a[data-section]")];
  const sections = [...links].map((link) => document.getElementById(link.dataset.section)).filter(Boolean);
  if (!links.length || !sections.length) return;

  let ticking = false;

  const setActiveSection = () => {
    ticking = false;
    const headerOffset = window.innerWidth > 900 ? 96 : 72;
    let activeSection = sections[0];
    let strongestVisibility = -1;

    sections.forEach((section, index) => {
      const rect = section.getBoundingClientRect();
      const visibleTop = Math.max(rect.top, headerOffset);
      const visibleBottom = Math.min(rect.bottom, window.innerHeight);
      const visiblePixels = Math.max(0, visibleBottom - visibleTop);
      const sectionHasPassedHeader = rect.top <= headerOffset + 24;

      if (visiblePixels > strongestVisibility || (visiblePixels === strongestVisibility && sectionHasPassedHeader && index > 0)) {
        strongestVisibility = visiblePixels;
        activeSection = section;
      }
    });

    links.forEach((link) => {
      link.classList.toggle("is-active", link.dataset.section === activeSection.id);
    });
  };

  const requestUpdate = () => {
    if (ticking) return;
    ticking = true;
    window.requestAnimationFrame(setActiveSection);
  };

  setActiveSection();
  window.addEventListener("scroll", requestUpdate, { passive: true });
  window.addEventListener("resize", requestUpdate);
}

